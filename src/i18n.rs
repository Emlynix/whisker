const COUNT: usize = T::MacroWarn as usize + 1;
type Table = [&'static str; COUNT];

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Sk,
    Cs,
    Pl,
    De,
    Fr,
    Es,
    Pt,
    It,
    Ja,
    Ko,
    ZhHans,
    ZhHant,
}

impl Lang {
    pub const ALL: [Lang; 13] = [
        Lang::En, Lang::Sk, Lang::Cs, Lang::Pl, Lang::De, Lang::Fr, Lang::Es,
        Lang::Pt, Lang::It, Lang::Ja, Lang::Ko, Lang::ZhHans, Lang::ZhHant,
    ];

    /// Stable id used in the config file.
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Sk => "sk",
            Lang::Cs => "cs",
            Lang::Pl => "pl",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::Pt => "pt",
            Lang::It => "it",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::ZhHans => "zh-Hans",
            Lang::ZhHant => "zh-Hant",
        }
    }

    /// Name in the language itself, shown in the picker.
    pub fn native(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Sk => "Slovenčina",
            Lang::Cs => "Čeština",
            Lang::Pl => "Polski",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::Pt => "Português",
            Lang::It => "Italiano",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::ZhHans => "简体中文",
            Lang::ZhHant => "繁體中文",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        Lang::ALL.into_iter().find(|l| l.code() == code)
    }

    fn table(self) -> &'static Table {
        match self {
            Lang::En => &EN,
            Lang::Sk => &SK,
            Lang::Cs => &CS,
            Lang::Pl => &PL,
            Lang::De => &DE,
            Lang::Fr => &FR,
            Lang::Es => &ES,
            Lang::Pt => &PT,
            Lang::It => &IT,
            Lang::Ja => &JA,
            Lang::Ko => &KO,
            Lang::ZhHans => &ZH_HANS,
            Lang::ZhHant => &ZH_HANT,
        }
    }
}

static CURRENT: AtomicUsize = AtomicUsize::new(0);

pub fn set_lang(l: Lang) {
    let i = Lang::ALL.iter().position(|&x| x == l).unwrap_or(0);
    CURRENT.store(i, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    Lang::ALL[CURRENT.load(Ordering::Relaxed)]
}

pub fn tr(k: T) -> &'static str {
    lang().table()[k as usize]
}

/// Replaces each `{}` with the next argument: `fill("{} of {}", &["2", "6"])`.
pub fn fill(s: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut rest = s;
    for a in args {
        let Some(i) = rest.find("{}") else {
            break;
        };
        out.push_str(&rest[..i]);
        out.push_str(a);
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

/// Windows UI language mapped to a supported one, English otherwise.
pub fn system_lang() -> Lang {
    const PRIMARY_MASK: u16 = 0x3FF;
    let id = unsafe { GetUserDefaultUILanguage() };

    // Chinese: Traditional for Taiwan (0x0404), Hong Kong (0x0C04), Macau (0x1404).
    if id & PRIMARY_MASK == 0x04 {
        return if matches!(id, 0x0404 | 0x0C04 | 0x1404) { Lang::ZhHant } else { Lang::ZhHans };
    }
    match id & PRIMARY_MASK {
        0x1B => Lang::Sk,
        0x05 => Lang::Cs,
        0x15 => Lang::Pl,
        0x07 => Lang::De,
        0x0C => Lang::Fr,
        0x0A => Lang::Es,
        0x16 => Lang::Pt,
        0x10 => Lang::It,
        0x11 => Lang::Ja,
        0x12 => Lang::Ko,
        _ => Lang::En,
    }
}

