#[cfg(not(test))]
static CURRENT: AtomicUsize = AtomicUsize::new(0);

// Tests run in parallel: each test thread keeps its own language.
#[cfg(test)]
thread_local! {
    static CURRENT: AtomicUsize = const { AtomicUsize::new(0) };
}

/// Runs `f` on the index of the UI language in `Lang::ALL`.
fn current<R>(f: impl FnOnce(&AtomicUsize) -> R) -> R {
    #[cfg(not(test))]
    return f(&CURRENT);
    #[cfg(test)]
    return CURRENT.with(f);
}

pub fn set_lang(l: Lang) {
    let i = Lang::ALL.iter().position(|&x| x == l).unwrap_or(0);
    current(|c| c.store(i, Ordering::Relaxed));
}

pub fn lang() -> Lang {
    Lang::ALL[current(|c| c.load(Ordering::Relaxed))]
}

pub fn tr(k: T) -> &'static str {
    lang().table()[k as usize]
}

/// Runs `f` with texts in `l`, then restores the UI language; e.g. a
/// support report in English (UI thread only).
pub fn with_lang<R>(l: Lang, f: impl FnOnce() -> R) -> R {
    let ui = lang();
    set_lang(l);
    let r = f();
    set_lang(ui);
    r
}

/// Replaces each `{}` with the next argument: `fill("{} of {}", &["2", "6"])`.
pub fn fill(s: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut rest = s;
    for a in args {
        let Some(i) = rest.find("{}") else {
            break;
        };
        out.push_str(&rest[..i]);
        out.push_str(a);
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

/// OS UI language mapped to a supported one, English otherwise.
pub fn system_lang() -> Lang {
    crate::platform::user_locale().map(|t| lang_of(&t)).unwrap_or(Lang::En)
}

/// Locale name to language, e.g. `"sk-SK"` -> Sk, `"zh_TW"` -> ZhHant.
fn lang_of(locale: &str) -> Lang {
    let lower = locale.to_lowercase().replace('_', "-");
    let mut parts = lower.split(['-', '.']);
    let primary = parts.next().unwrap_or_default();

    // Chinese: Traditional script, or Taiwan, Hong Kong, Macau.
    if primary == "zh" {
        let traditional = parts.any(|p| matches!(p, "hant" | "tw" | "hk" | "mo"));
        return if traditional { Lang::ZhHant } else { Lang::ZhHans };
    }
    match primary {
        "sk" => Lang::Sk,
        "cs" => Lang::Cs,
        "pl" => Lang::Pl,
        "de" => Lang::De,
        "fr" => Lang::Fr,
        "es" => Lang::Es,
        "pt" => Lang::Pt,
        "it" => Lang::It,
        "ja" => Lang::Ja,
        "ko" => Lang::Ko,
        _ => Lang::En,
    }
}

