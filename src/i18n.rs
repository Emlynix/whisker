impl Lang {
    pub const ALL: [Lang; 13] = [
        Lang::En, Lang::Sk, Lang::Cs, Lang::Pl, Lang::De, Lang::Fr, Lang::Es,
        Lang::Pt, Lang::It, Lang::Ja, Lang::Ko, Lang::ZhHans, Lang::ZhHant,
    ];

    /// Stable id used in the config file.
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Sk => "sk",
            Lang::Cs => "cs",
            Lang::Pl => "pl",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::Pt => "pt",
            Lang::It => "it",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::ZhHans => "zh-Hans",
            Lang::ZhHant => "zh-Hant",
        }
    }

    /// Name in the language itself, shown in the picker.
    pub fn native(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Sk => "Slovenčina",
            Lang::Cs => "Čeština",
            Lang::Pl => "Polski",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::Pt => "Português",
            Lang::It => "Italiano",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::ZhHans => "简体中文",
            Lang::ZhHant => "繁體中文",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        Lang::ALL.into_iter().find(|l| l.code() == code)
    }

    fn table(self) -> &'static Table {
        match self {
            Lang::En => &EN,
            Lang::Sk => &SK,
            Lang::Cs => &CS,
            Lang::Pl => &PL,
            Lang::De => &DE,
            Lang::Fr => &FR,
            Lang::Es => &ES,
            Lang::Pt => &PT,
            Lang::It => &IT,
            Lang::Ja => &JA,
            Lang::Ko => &KO,
            Lang::ZhHans => &ZH_HANS,
            Lang::ZhHant => &ZH_HANT,
        }
    }
}

static CURRENT: AtomicUsize = AtomicUsize::new(0);

pub fn set_lang(l: Lang) {
    let i = Lang::ALL.iter().position(|&x| x == l).unwrap_or(0);
    CURRENT.store(i, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    Lang::ALL[CURRENT.load(Ordering::Relaxed)]
}

pub fn tr(k: T) -> &'static str {
    lang().table()[k as usize]
}

/// Replaces each `{}` with the next argument: `fill("{} of {}", &["2", "6"])`.
pub fn fill(s: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut rest = s;
    for a in args {
        let Some(i) = rest.find("{}") else {
            break;
        };
        out.push_str(&rest[..i]);
        out.push_str(a);
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

/// OS UI language mapped to a supported one, English otherwise.
pub fn system_lang() -> Lang {
    crate::platform::user_locale().map(|t| lang_of(&t)).unwrap_or(Lang::En)
}

/// Locale name to language, e.g. `"sk-SK"` -> Sk, `"zh_TW"` -> ZhHant.
fn lang_of(locale: &str) -> Lang {
    let lower = locale.to_lowercase().replace('_', "-");
    let mut parts = lower.split(['-', '.']);
    let primary = parts.next().unwrap_or_default();

    // Chinese: Traditional script, or Taiwan, Hong Kong, Macau.
    if primary == "zh" {
        let traditional = parts.any(|p| matches!(p, "hant" | "tw" | "hk" | "mo"));
        return if traditional { Lang::ZhHant } else { Lang::ZhHans };
    }
    match primary {
        "sk" => Lang::Sk,
        "cs" => Lang::Cs,
        "pl" => Lang::Pl,
        "de" => Lang::De,
        "fr" => Lang::Fr,
        "es" => Lang::Es,
        "pt" => Lang::Pt,
        "it" => Lang::It,
        "ja" => Lang::Ja,
        "ko" => Lang::Ko,
        _ => Lang::En,
    }
}

